<script lang="ts">
  import { formatCurrency, formatUnits } from '../backtest'
  import type { StrategyComparison, TradeOrder } from '../strategies/types'

  export let comparisons: StrategyComparison[]
  export let coin: string

  $: orders = comparisons
    .flatMap((comparison) =>
      comparison.result.orders.map((order: TradeOrder) => ({
        ...order,
        strategy: comparison.strategy,
      })),
    )
    .sort((a, b) => b.timestamp - a.timestamp)
</script>

<section class="trade-history" aria-label="Strategy trade history">
  <div class="trade-history-heading">
    <div>
      <h2>Trade activity</h2>
      <p>Strategy orders executed at candle opens, including amount and fees.</p>
    </div>
    <span>{orders.length} orders</span>
  </div>

  {#if orders.length}
    <div class="trade-table-scroll">
      <table>
        <thead>
          <tr>
            <th>TIME</th>
            <th>STRATEGY</th>
            <th>SIDE</th>
            <th>QUANTITY</th>
            <th>PRICE</th>
            <th>NOTIONAL</th>
            <th>FEE</th>
          </tr>
        </thead>
        <tbody>
          {#each orders as order}
            <tr>
              <td>{new Date(order.timestamp).toLocaleString()}</td>
              <td>
                <span class="trade-strategy">
                  <i style={`--strategy-color: ${order.strategy.color}`}></i>
                  {order.strategy.name}
                </span>
              </td>
              <td class:trade-buy={order.side === 'buy'} class:trade-sell={order.side === 'sell'}>
                {order.side.toUpperCase()}
              </td>
              <td>{formatUnits(order.quantity)} {coin}</td>
              <td>{formatCurrency(order.price)}</td>
              <td>{formatCurrency(order.notional)}</td>
              <td>{formatCurrency(order.fee)}</td>
            </tr>
          {/each}
        </tbody>
      </table>
    </div>
  {:else}
    <div class="trade-history-empty">No buy or sell orders were generated by the selected strategies.</div>
  {/if}
</section>

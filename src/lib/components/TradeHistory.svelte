<script lang="ts">
  import { formatCurrency, formatNumber, formatUnits } from '../backtest'
  import type { IdentifiedTradeOrder, StrategyComparison } from '../strategies/types'

  export let comparisons: StrategyComparison[]
  export let coin: string
  export let quoteCurrency: string
  export let marketType: 'perpetual' | 'forex'
  export let selectedStrategyId: string | null
  export let hoveredOrder: IdentifiedTradeOrder | null
  export let onHoverOrder: (order: IdentifiedTradeOrder | null) => void

  $: orders = comparisons
    .filter((comparison) => selectedStrategyId === null || comparison.strategy.id === selectedStrategyId)
    .flatMap((comparison) =>
      comparison.result.orders.map((order) => ({
        ...order,
        strategyId: comparison.strategy.id,
        strategy: comparison.strategy,
      })),
    )
    .sort((a, b) => b.timestamp - a.timestamp)
</script>

<section class="trade-history" aria-label="Strategy trade history">
  <div class="trade-history-heading">
    <div>
      <h2>Trade activity</h2>
      <p>Orders execute at the next available candle open or daily reference observation.</p>
    </div>
    <span>{orders.length} orders</span>
  </div>

  {#if orders.length}
    <div class="trade-table-scroll">
      <table>
        <thead>
          <tr>
            <th>TIME</th>
            <th>STRATEGY</th>
            <th>SIDE</th>
            <th>QUANTITY</th>
            <th>PRICE</th>
            <th>NOTIONAL</th>
            <th>FEE</th>
          </tr>
        </thead>
        <tbody>
          {#each orders as order}
            <tr
              class:trade-row-hovered={hoveredOrder?.strategyId === order.strategyId && hoveredOrder?.timestamp === order.timestamp && hoveredOrder?.side === order.side && hoveredOrder?.price === order.price}
              on:mouseenter={() => onHoverOrder(order)}
              on:mouseleave={() => onHoverOrder(null)}
            >
              <td>{new Date(order.timestamp).toLocaleString()}</td>
              <td>
                <span class="trade-strategy">
                  <i style={`--strategy-color: ${order.strategy.color}`}></i>
                  {order.strategy.name}
                </span>
              </td>
              <td class:trade-buy={order.side === 'buy'} class:trade-sell={order.side === 'sell'}>
                {order.side.toUpperCase()}
              </td>
              <td>{formatUnits(order.quantity)} {coin}</td>
              <td>{marketType === 'forex'
                ? `${formatNumber(order.price, 5)} ${quoteCurrency}`
                : formatCurrency(order.price, quoteCurrency)}</td>
              <td>{formatCurrency(order.notional, quoteCurrency)}</td>
              <td>{formatCurrency(order.fee, quoteCurrency)}</td>
            </tr>
          {/each}
        </tbody>
      </table>
    </div>
  {:else}
    <div class="trade-history-empty">No buy or sell orders were generated by the selected strategy.</div>
  {/if}
</section>
